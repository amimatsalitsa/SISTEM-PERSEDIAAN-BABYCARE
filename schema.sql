-- BabyCare: empat entitas inti. Jalankan di Supabase SQL Editor.

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text,
  created_at timestamptz not null default now()
);

create table if not exists public.suppliers (
  id bigint generated by default as identity primary key,
  name text not null,
  contact_name text,
  phone text,
  email text,
  address text,
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  sku text not null unique,
  name text not null,
  category_id bigint not null references public.categories(id) on delete restrict,
  supplier_id bigint not null references public.suppliers(id) on delete restrict,
  unit text not null default 'pcs',
  varian text,
  tanggal_kadaluarsa date,
  price numeric(14, 2) not null default 0 check (price >= 0),
  stock integer not null default 0 check (stock >= 0),
  min_stock integer not null default 5 check (min_stock >= 0),
  created_at timestamptz not null default now()
);

-- Aman dijalankan juga pada basis data BabyCare yang tabel products-nya sudah ada.
alter table public.products add column if not exists varian text;
alter table public.products add column if not exists tanggal_kadaluarsa date;
alter table public.products alter column min_stock set default 5;
update public.products set min_stock = 5 where min_stock = 0;

do $$
begin
  if not exists (select 1 from pg_constraint where conrelid = 'public.products'::regclass and conname = 'products_price_nonnegative') then
    alter table public.products add constraint products_price_nonnegative check (price >= 0);
  end if;
  if not exists (select 1 from pg_constraint where conrelid = 'public.products'::regclass and conname = 'products_stock_nonnegative') then
    alter table public.products add constraint products_stock_nonnegative check (stock >= 0);
  end if;
  if not exists (select 1 from pg_constraint where conrelid = 'public.products'::regclass and conname = 'products_min_stock_nonnegative') then
    alter table public.products add constraint products_min_stock_nonnegative check (min_stock >= 0);
  end if;
end;
$$;

create table if not exists public.stock_movements (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete restrict,
  type text not null check (type in ('in', 'out')),
  quantity integer not null check (quantity > 0),
  notes text,
  created_at timestamptz not null default now()
);

create index if not exists products_category_id_idx on public.products(category_id);
create index if not exists products_supplier_id_idx on public.products(supplier_id);
create index if not exists products_expiration_idx on public.products(tanggal_kadaluarsa) where tanggal_kadaluarsa is not null;
create index if not exists stock_movements_product_created_idx on public.stock_movements(product_id, created_at desc);

-- Mencegah perubahan stok langsung; hanya trigger pergerakan stok yang boleh mengubahnya.
create or replace function public.prevent_direct_stock_change()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' and new.stock <> 0 and pg_trigger_depth() = 1 then
    raise exception 'Stok awal harus dicatat sebagai pergerakan stok.' using errcode = '23514';
  end if;
  if tg_op = 'UPDATE' and new.stock is distinct from old.stock and pg_trigger_depth() = 1 then
    raise exception 'Stok hanya boleh diubah melalui pergerakan stok.' using errcode = '23514';
  end if;
  return new;
end;
$$;

drop trigger if exists products_stock_requires_movement on public.products;
create trigger products_stock_requires_movement
before insert or update of stock on public.products
for each row execute function public.prevent_direct_stock_change();

-- Setiap pergerakan stok menjadi audit log dan mengubah stok secara atomik.
create or replace function public.apply_stock_movement()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
  stock_delta integer;
begin
  stock_delta := case when new.type = 'in' then new.quantity else -new.quantity end;
  update public.products
    set stock = stock + stock_delta
    where id = new.product_id and stock + stock_delta >= 0;

  if not found then
    raise exception 'Stok produk tidak cukup untuk pergerakan keluar.' using errcode = '23514';
  end if;

  return new;
end;
$$;

drop trigger if exists stock_movement_updates_product_stock on public.stock_movements;
create trigger stock_movement_updates_product_stock
after insert on public.stock_movements
for each row execute function public.apply_stock_movement();

